class ScopeViolation(PermissionError):
    """Raised when an execution context touches a resource outside its scope."""

    def __init__(self, code: str, *, fields: Iterable[str] = (), detail: str = "") -> None:
        self.code = code
        self.fields = tuple(dict.fromkeys(fields))
        message = code
        if self.fields:
            message = f"{code} (fields: {', '.join(self.fields)})"
        if detail:
            message = f"{message}: {detail}"
        super().__init__(message)


class ExecutionContext(BaseModel):
    """Identity of one workflow execution.

    ``tenant_id`` and ``owner_id`` are mandatory: a workflow never runs "unowned".
    Optional dimensions only widen the isolation checks when they are present.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    tenant_id: str
    owner_id: str
    service_id: Optional[str] = None
    session_id: Optional[str] = None
    conversation_id: Optional[str] = None
    workspace_id: Optional[str] = None

    @field_validator("tenant_id", "owner_id")
    @classmethod
    def _validate_scope_identifiers(cls, value: str) -> str:
        return validate_scope_identifier(value, "scope_id")

    @field_validator("service_id", "session_id", "conversation_id", "workspace_id")
    @classmethod
    def _validate_optional(cls, value: Optional[str]) -> Optional[str]:
        if value is None:
            return None
        cleaned = value.strip()
        if not cleaned:
            raise ValueError("empty_scope_identifier")
        return cleaned

    def scope_map(self) -> Dict[str, Optional[str]]:
        return {field: getattr(self, field) for field in SCOPE_FIELDS}

    def scope_hash(self) -> str:
        """Stable digest of all scope dimensions — the binding used by approval tokens."""
        payload = json.dumps(self.scope_map(), sort_keys=True, separators=(",", ":"))
        return "sha256:" + hashlib.sha256(payload.encode("utf-8")).hexdigest()

    def same_scope(self, other: "ExecutionContext") -> bool:
        return self.scope_hash() == other.scope_hash()


class ScopedResource(BaseModel):
    """A resource (file, conversation, tool result, MCP resource…) with declared scope."""

    model_config = ConfigDict(extra="allow")

    tenant_id: Optional[str] = None
    owner_id: Optional[str] = None
    service_id: Optional[str] = None
    session_id: Optional[str] = None
    conversation_id: Optional[str] = None
    workspace_id: Optional[str] = None


def _scope_payload(resource: Optional[Any]) -> Dict[str, Any]:
    if resource is None:
        return {}
    if isinstance(resource, Mapping):
        return {key: resource.get(key) for key in SCOPE_FIELDS if resource.get(key) is not None}
    data = getattr(resource, "__dict__", None)
    if isinstance(data, Mapping):
        return {key: data.get(key) for key in SCOPE_FIELDS if data.get(key) is not None}
    return {key: getattr(resource, key) for key in SCOPE_FIELDS if getattr(resource, key, None) is not None}


def assert_scope_access(
    context: ExecutionContext,
    resource: Optional[Any] = None,
    *,
    require: Iterable[str] = ("tenant_id",),
) -> bool:
    """Verify that ``context`` may act on ``resource``.

    Rules (deny-by-default):

    * every scope dimension declared by the resource must be present in the context and
      equal to it;
    * every dimension listed in ``require`` must be declared by the resource, so a
      resource without ownership can never be treated as a shared/global object by
      accident;
    * an unknown dimension in ``require`` is a programming error and is rejected.

    Returns ``True`` on success and raises :class:`ScopeViolation` otherwise.
    """
    required = tuple(require)
    unknown = [field for field in required if field not in SCOPE_FIELDS]
    if unknown:
        raise ValueError(f"unknown_scope_fields: {', '.join(unknown)}")

    declared = _scope_payload(resource)

    missing = [field for field in required if field not in declared]
    if missing:
        raise ScopeViolation("unscoped_resource", fields=missing)

    mismatched: List[str] = []
    for field, value in declared.items():
        expected = getattr(context, field)
        if expected is None:
            mismatched.append(field)
            continue
        if str(expected) != str(value):
            mismatched.append(field)
    if mismatched:
        raise ScopeViolation("scope_mismatch", fields=mismatched)

    return True


