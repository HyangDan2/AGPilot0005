"""WP-10 Execution Safety for the R3 workflow engine.

This module keeps every R3 cross-cutting safety primitive in one place so the planner,
the tool dispatcher and the concrete adapters can share the same enforcement:

* :class:`ExecutionContext` — tenant / owner / service / session / conversation /
  workspace scoping with deny-by-default access checks (:func:`assert_scope_access`).
* :class:`ApprovalAuthority` — issues and verifies approval tokens.  An approval that
  was generated by the model is structurally different from an explicit user approval
  and can never pass :meth:`ApprovalAuthority.verify_user_approval`.
* :class:`PromptInjectionGuard` — detects instruction-shaped text coming from external
  MCP servers, documents and tool output, and wraps it as clearly delimited untrusted
  data instead of letting it reach the prompt bare.
* :class:`IdempotencyLedger` — prevents a retried step from repeating an external side
  effect twice for the same ``step_id + idempotency_key``.

The module is dependency-light on purpose (pydantic + stdlib) so it can be reused by
the runtime, by tests and by the acceptance scenarios without booting FastAPI.
"""
