class IdempotencyError(RuntimeError):
    pass


class IdempotencyConflict(IdempotencyError):
    """Raised when a step is executed twice with the same idempotency key."""

    def __init__(self, code: str, record: "IdempotencyRecord") -> None:
        self.code = code
        self.record = record
        super().__init__(f"{code}: step_id={record.step_id} key={record.idempotency_key} status={record.status}")


class IdempotencyRecord(BaseModel):
    model_config = ConfigDict(extra="forbid")

    step_id: str
    idempotency_key: str
    scope_key: str = "-"
    status: Literal["in_flight", "completed", "failed"] = "in_flight"
    result: Any = None
    error: Optional[str] = None
    attempts: int = 1
    created_at: datetime
    updated_at: datetime


class IdempotencyLedger:
    """Prevents duplicate external side effects for ``step_id + idempotency_key``.

    The key is additionally namespaced by ``scope_key`` (normally the execution scope
    hash) so two tenants that happen to reuse the same planner-generated keys never
    observe each other's results.
    """

    def __init__(self) -> None:
        self._records: Dict[Tuple[str, str, str], IdempotencyRecord] = {}
        self._lock = threading.RLock()

    @staticmethod
    def _validate(step_id: str, key: str) -> None:
        if not step_id or not str(step_id).strip():
            raise IdempotencyError("step_id_required")
        if not key or not str(key).strip():
            raise IdempotencyError("idempotency_key_required")

    @staticmethod
    def scope_key(context: Optional[ExecutionContext] = None, scope_key: Optional[str] = None) -> str:
        if scope_key:
            return scope_key
        return context.scope_hash() if context is not None else "-"

    def _k(self, step_id: str, key: str, scope_key: str) -> Tuple[str, str, str]:
        return (scope_key, step_id, key)

    def lookup(self, step_id: str, idempotency_key: str, *, scope_key: Optional[str] = None,
               context: Optional[ExecutionContext] = None) -> Optional[IdempotencyRecord]:
        with self._lock:
            return self._records.get(self._k(step_id, idempotency_key, self.scope_key(context, scope_key)))

    def begin(
        self,
        step_id: str,
        idempotency_key: str,
        *,
        scope_key: Optional[str] = None,
        context: Optional[ExecutionContext] = None,
    ) -> IdempotencyRecord:
        """Reserve the key.  Raises :class:`IdempotencyConflict` when already used."""
        self._validate(step_id, idempotency_key)
        key = self._k(step_id, idempotency_key, self.scope_key(context, scope_key))
        now = _utcnow()
        with self._lock:
            existing = self._records.get(key)
            if existing is not None:
                replayable = existing.status == "failed"
                if not replayable:
                    raise IdempotencyConflict("duplicate_step", existing)
                record = existing.model_copy(update={
                    "status": "in_flight",
                    "attempts": existing.attempts + 1,
                    "error": None,
                    "updated_at": now,
                })
                self._records[key] = record
                return record
            record = IdempotencyRecord(
                step_id=step_id,
                idempotency_key=idempotency_key,
                scope_key=key[0],
                status="in_flight",
                created_at=now,
                updated_at=now,
            )
            self._records[key] = record
            return record

    def complete(self, step_id: str, idempotency_key: str, result: Any = None, *,
                 scope_key: Optional[str] = None,
                 context: Optional[ExecutionContext] = None) -> IdempotencyRecord:
        self._validate(step_id, idempotency_key)
        key = self._k(step_id, idempotency_key, self.scope_key(context, scope_key))
        with self._lock:
            record = self._records.get(key)
            if record is None:
                raise IdempotencyError("unknown_idempotency_key")
            updated = record.model_copy(update={
                "status": "completed",
                "result": result,
                "error": None,
                "updated_at": _utcnow(),
            })
            self._records[key] = updated
            return updated

    def fail(self, step_id: str, idempotency_key: str, error: str, *,
             scope_key: Optional[str] = None,
             context: Optional[ExecutionContext] = None) -> IdempotencyRecord:
        self._validate(step_id, idempotency_key)
        key = self._k(step_id, idempotency_key, self.scope_key(context, scope_key))
        with self._lock:
            record = self._records.get(key)
            if record is None:
                raise IdempotencyError("unknown_idempotency_key")
            updated = record.model_copy(update={
                "status": "failed",
                "error": error,
                "updated_at": _utcnow(),
            })
            self._records[key] = updated
            return updated

    def run(
        self,
        step_id: str,
        idempotency_key: str,
        operation: Callable[[], Any],
        *,
        scope_key: Optional[str] = None,
        context: Optional[ExecutionContext] = None,
    ) -> Tuple[Any, bool]:
        """Execute ``operation`` exactly once; return ``(result, replayed)``.

        A completed record returns the cached result with ``replayed=True`` and the
        operation is not called again.  A failed record is retried (attempts++).
        """
        existing = self.lookup(step_id, idempotency_key, scope_key=scope_key, context=context)
        if existing is not None and existing.status == "completed":
            return existing.result, True
        self.begin(step_id, idempotency_key, scope_key=scope_key, context=context)
        try:
            result = operation()
        except Exception as exc:  # noqa: BLE001 - recorded then re-raised
            self.fail(step_id, idempotency_key, f"{type(exc).__name__}: {exc}", scope_key=scope_key, context=context)
            raise
        self.complete(step_id, idempotency_key, result, scope_key=scope_key, context=context)
        return result, False

    def records(self) -> List[IdempotencyRecord]:
        with self._lock:
            return list(self._records.values())

    def reset(self) -> None:
        with self._lock:
            self._records.clear()

    def __len__(self) -> int:
        with self._lock:
            return len(self._records)
