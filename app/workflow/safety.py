#: Every dimension a workflow resource can be scoped by.  The order is used for hashing
#: and for deterministic error reporting.
SCOPE_FIELDS: Tuple[str, ...] = (
    "tenant_id",
    "owner_id",
    "service_id",
    "session_id",
    "conversation_id",
    "workspace_id",
)


def _utcnow() -> datetime:
    return datetime.now(timezone.utc)


